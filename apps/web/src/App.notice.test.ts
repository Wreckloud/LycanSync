import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import { parse } from '@vue/compiler-sfc';
import ts from 'typescript';
import { effectScope, nextTick, reactive, ref, watch } from 'vue';
import { expect, it, vi } from 'vitest';
import { useNotice } from './feedback/useNotice';

const script = parse(readFileSync(new URL('./App.vue', import.meta.url), 'utf8')).descriptor.scriptSetup!.content;
const start = script.indexOf('const appNotice =');
const source = ts.transpile(script.slice(start, script.indexOf('const settingsReturnFocus', start)));

it('关闭只移除展示，旧错误不挡成功，同文案的新操作重新展示', async () => {
  const scope = effectScope();
  const rtc = reactive(useNotice());
  rtc.notice = '连接失败';
  const { notice: viewerNotice, noticeEvent: viewerNoticeEvent } = useNotice();
  const recording = { ...useNotice(), successNotice: ref<{ message: string } | null>(null) };
  const audioOutput = { notice: ref('') };
  const audioPreferences = { persistenceError: ref('') };
  const settingsOpen = ref(false);
  const settingsSection = ref('account');
  const props = reactive({ startupUpdateWarning: '' });
  const emit = vi.fn();
  const state = scope.run(() => runInNewContext(`${source}\n({ appNotice, dismissAppNotice })`, {
    ref, watch, rtc, viewerNoticeEvent, recording, audioOutput, audioPreferences, settingsOpen, settingsSection, props, emit,
  })) as { appNotice: { value: { id: number; message: string; kind?: string } | null }; dismissAppNotice(): void };
  try {
    expect(state.appNotice.value?.message).toBe('连接失败');
    state.dismissAppNotice();
    expect(state.appNotice.value).toBeNull();
    expect(rtc.notice).toBe('连接失败');
    rtc.notice = '连接失败';
    await nextTick();
    expect(state.appNotice.value?.message).toBe('连接失败');
    state.dismissAppNotice();
    viewerNotice.value = '无法切换全屏';
    await nextTick();
    state.dismissAppNotice();
    viewerNotice.value = '无法切换全屏';
    await nextTick();
    expect(state.appNotice.value?.message).toBe('无法切换全屏');
    recording.successNotice.value = { message: '回放已保存到本地录像' };
    await nextTick();
    expect(state.appNotice.value?.kind).toBe('success');
    const id = state.appNotice.value?.id;
    recording.successNotice.value = { message: '回放已保存到本地录像' };
    await nextTick();
    expect(state.appNotice.value?.id).not.toBe(id);
    expect(state.appNotice.value?.message).toBe('回放已保存到本地录像');
    state.dismissAppNotice();
    settingsOpen.value = true;
    settingsSection.value = 'recording';
    recording.notice.value = '保存目录不可用';
    await nextTick();
    expect(state.appNotice.value).toBeNull();
    expect(recording.notice.value).toBe('保存目录不可用');
    settingsSection.value = 'account';
    recording.notice.value = '保存目录不可用';
    await nextTick();
    expect(state.appNotice.value?.message).toBe('保存目录不可用');
    settingsSection.value = 'recording';
    await nextTick();
    expect(state.appNotice.value).toBeNull();
    audioOutput.notice.value = '输出设备不可用';
    await nextTick();
    expect(state.appNotice.value?.message).toBe('输出设备不可用');
    settingsSection.value = 'audio';
    await nextTick();
    expect(state.appNotice.value).toBeNull();
    audioOutput.notice.value = '切换失败';
    await nextTick();
    expect(state.appNotice.value).toBeNull();
    expect(audioOutput.notice.value).toBe('切换失败');
    audioPreferences.persistenceError.value = '声音设置已生效，但未能保存。';
    await nextTick();
    expect(state.appNotice.value).toBeNull();
    audioPreferences.persistenceError.value = '';
    settingsOpen.value = false;
    await nextTick();
    audioPreferences.persistenceError.value = '声音设置已生效，但未能保存。';
    await nextTick();
    expect(state.appNotice.value?.message).toBe('声音设置已生效，但未能保存。');
    settingsOpen.value = true;
    await nextTick();
    expect(state.appNotice.value).toBeNull();
    settingsOpen.value = false;
    audioPreferences.persistenceError.value = '';
    await nextTick();
    audioPreferences.persistenceError.value = '声音设置已生效，但未能保存。';
    await nextTick();
    audioPreferences.persistenceError.value = '';
    await nextTick();
    expect(state.appNotice.value).toBeNull();
    props.startupUpdateWarning = '更新失败';
    await nextTick();
    state.dismissAppNotice();
    expect(emit).toHaveBeenCalledWith('dismissUpdateWarning');
  } finally { scope.stop(); }
});
